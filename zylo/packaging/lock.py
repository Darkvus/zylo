"""`zylo.lock`: the exact commit and checksum of every installed package."""
import json
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

from zylo.domain.errors import PackageError

LOCK = "zylo.lock"


@dataclass
class LockEntry:
    """One locked package.

    Attributes:
        name: Package name.
        source: Normalized git URL, or `path:<dir>`.
        ref: The tag, branch or commit that was requested.
        commit: The exact commit installed (None for path dependencies).
        checksum: Hash of the installed files.
        version: The package's declared version.
    """
    name: str
    source: str            # normalized git URL, or `path:<dir>`
    ref: str | None
    commit: str | None
    checksum: str
    version: str = ""


@dataclass
class Lock:
    """The lock file: every installed package by name.

    Attributes:
        entries: Locked packages by name.
    """
    entries: dict[str, LockEntry] = field(default_factory=dict)


def load_lock(path: Path) -> Lock:
    """Read `zylo.lock`.

    Args:
        path: The lock file.

    Returns:
        The lock, empty if the file does not exist.

    Raises:
        PackageError: If the file is not valid.
    """
    if not path.is_file():
        return Lock()
    try:
        data = tomllib.loads(path.read_text())
        entries = {}
        for p in data.get("package", []):
            e = LockEntry(p["name"], p["source"], p.get("ref"), p.get("commit"), p["checksum"], p.get("version", ""))
            entries[e.name] = e
        return Lock(entries)
    except (OSError, tomllib.TOMLDecodeError, KeyError) as e:
        raise PackageError(f"{path}: invalid lock file ({e}); delete it and run `zylo install`") from None


def dump_lock(lock: Lock) -> str:
    """Render a lock file.

    Args:
        lock: The lock.

    Returns:
        TOML text with packages sorted by name, so the file is stable.
    """
    out = ["# This file is generated by `zylo`; do not edit it by hand.", "version = 1"]
    for name in sorted(lock.entries):
        e = lock.entries[name]
        out += ["", "[[package]]", f"name = {json.dumps(e.name)}"]
        if e.version:
            out.append(f"version = {json.dumps(e.version)}")
        out.append(f"source = {json.dumps(e.source)}")
        if e.ref:
            out.append(f"ref = {json.dumps(e.ref)}")
        if e.commit:
            out.append(f"commit = {json.dumps(e.commit)}")
        out.append(f"checksum = {json.dumps(e.checksum)}")
    return "\n".join(out) + "\n"
